import fs from "node:fs";

// CSV is the source of truth, including quoted fields and optional UTF-8 BOM.
const text = fs
  .readFileSync("data/gold-schema.csv", "utf8")
  .replace(/^\uFEFF/, "");
const records = [];
let record = [],
  field = "",
  quoted = false;
for (let i = 0; i < text.length; i++) {
  const char = text[i];
  if (char === '"') {
    if (quoted && text[i + 1] === '"') {
      field += '"';
      i++;
    } else quoted = !quoted;
  } else if (char === "," && !quoted) {
    record.push(field);
    field = "";
  } else if ((char === "\n" || char === "\r") && !quoted) {
    if (char === "\r" && text[i + 1] === "\n") i++;
    record.push(field);
    if (record.some((value) => value.trim())) records.push(record);
    record = [];
    field = "";
  } else field += char;
}
if (quoted) throw new Error("Unclosed CSV quote");
if (field || record.length) {
  record.push(field);
  records.push(record);
}
const headers = records.shift().map((value) => value.trim());
for (const name of ["table_name", "column_name", "data_type"])
  if (!headers.includes(name)) throw new Error(`Missing CSV field ${name}`);
const rows = records.map((values) =>
  Object.fromEntries(
    ["table_name", "column_name", "data_type"].map((name) => [
      name,
      values[headers.indexOf(name)]?.trim(),
    ]),
  ),
);
if (!rows.length) throw new Error("The schema CSV is empty");
const tables = new Map();
const types = {
  STRING: "string",
  DATE: "string",
  TIMESTAMP: "string",
  INT: "number",
  LONG: "string",
  DECIMAL: "string",
  DOUBLE: "number",
};
for (const row of rows) {
  if (
    !/^[a-z][a-z0-9_]*$/.test(row.table_name) ||
    !/^[a-z_][a-z0-9_]*$/.test(row.column_name)
  )
    throw new Error("Invalid source identifier");
  if (!types[row.data_type])
    throw new Error(`Unsupported type: ${row.data_type}`);
  const columns = tables.get(row.table_name) ?? [];
  if (columns.some((column) => column.column_name === row.column_name))
    throw new Error("Duplicate schema column");
  columns.push(row);
  tables.set(row.table_name, columns);
}
const lines = [
  "// Generated by scripts/generate-schema.mjs from the supplied CSV contract.",
  "// Nullability was not supplied. LONG and DECIMAL retain exact string representations.",
  "export interface GoldRows {",
];
for (const [table, columns] of tables) {
  lines.push(`  ${table}: {`);
  for (const column of columns)
    lines.push(`    ${column.column_name}: ${types[column.data_type]} | null;`);
  lines.push("  };");
}
lines.push("}", "");
fs.mkdirSync("src/lib/server", { recursive: true });
fs.writeFileSync("data/gold-schema.json", JSON.stringify(rows, null, 2) + "\n");
fs.writeFileSync("src/lib/server/gold-rows.ts", lines.join("\n"));
const principal = "`<app-service-principal-application-id>`";
const catalog = "`<your-catalog>`";
const schema = "`<your-schema>`";
fs.writeFileSync(
  "scripts/grants.sql",
  [
    "-- Generated from the supplied schema contract. An authorized administrator runs this.",
    "-- Replace the three placeholders. This script does not create or modify source data.",
    `GRANT USE CATALOG ON CATALOG ${catalog} TO ${principal};`,
    `GRANT USE SCHEMA ON SCHEMA ${catalog}.${schema} TO ${principal};`,
    ...[...tables.keys()]
      .sort()
      .map(
        (table) =>
          `GRANT SELECT ON TABLE ${catalog}.${schema}.\`${table}\` TO ${principal};`,
      ),
    "",
  ].join("\n"),
);
console.log(
  `Generated ${tables.size} tables / ${rows.length} exact column types.`,
);
